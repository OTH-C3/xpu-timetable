/*
 * GlassTokens.kt —— 玻璃卡（卡片透明度）的调节参数（M13）
 *
 * 为什么要从 Tokens.kt 搬出来：它与 `GlassPalette` 的**可读性下限**是同一个决策的
 * 两面（滑块下限必须与颜色夹紧下限一致，否则用户能拖出"画面不动只数字跳"的区间）。
 * 放在一起能一眼看到这层耦合；而放回 Tokens.kt 会把它埋进一堆无关的待办/列表令牌里，
 * 而且 Tokens.kt 本身已顶到 300 行门禁。
 */

package com.gould.xputimetable.ui.theme

object GlassCard {
    /**
     * 滑块下限。
     *
     * 必须与 GlassPalette 的 GLASS_MIN_ALPHA **取同一个数**（单测钉死相等）：
     * 滑块比下限还低的话，用户能拖出"文字读不清"的位置，而那个位置在别处
     * 又被玻璃色自己夹回来 —— 结果是拖了半天画面不动，只剩数字在跳。
     *
     * 为什么是 0.30（2026-10-04 实测，旧值 0.50）：
     *   实测口径 = 卡片色以 alpha 叠在"卡片正下方的实际底色"上，再算 onSurface 文字
     *   （#1A1C1E）与 bodySmall 副文本（#43474E）对结果的 WCAG 对比度；
     *   页面底色 LightPageBackground = RGB(221,224,241)。
     *     · 无背景图（白卡 over 页面底色）：alpha 0.30 → 正文 14.17:1、副文本 7.74:1；
     *     · 默认不透明度 0.18 且换上一张纯黑图（卡片底下 = RGB(181,184,198)）：
     *       alpha 0.30 → 正文 9.50:1、副文本 5.19:1，仍然全部高于 4.5:1。
     *   也就是说"正文跌破 4.5:1"这件事**根本不在 0.30 附近发生**；旧下限 0.50 的真实
     *   作用其实是挤掉了"卡片已经薄到只剩描边在撑"的那一段，而不是对比度倒推出来的。
     *   0.30 是这个"卡片还算一个面"的位置实测下来最靠外的点，同时给 4.5:1 留了 2 倍余量。
     *
     * ⚠️ 唯一会跌破 4.5:1 的组合是把**背景不透明度拉到 100% 且背景图本身纯黑**：
     *   那种情况下 alpha 0.50 实测也只有 3.20:1（比 0.30 更低只会更糟）——
     *   该位置该管的是"背景图不透明度"，不该让卡片下限去背锅，否则下限永远动不了。
     */
    const val MinAlpha = 0.30f

    /** 上限。1 = 完全不透明（彻底关掉玻璃感），留给觉得"卡片该是实心"的用户。 */
    const val MaxAlpha = 1f

    /** 步长数：从 [MinAlpha] 起每 1% 一档（(1 - 0.30) / 0.01 = 70，共 71 个刻度含两端）。 */
    const val Steps = 70
}
