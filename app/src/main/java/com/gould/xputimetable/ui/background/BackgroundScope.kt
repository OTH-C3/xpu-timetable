/*
 * BackgroundScope.kt —— 自定义背景的作用域（M12 需求二）
 *
 * 为什么要有「作用域」：同一张背景图，铺在全部页面上会让编辑表单的输入框、导入预览的
 * 卡片全部压上花纹，可读性下降；而只铺课表页又太少用。于是把"这张图作用在哪些页"做成
 * 一个可枚举的选择（全局 / 课表 / 我的 / 便签），由用户在设置页勾选。
 *
 * 判定为什么放在这里而不是各页面自报家门：
 *   AppScreen 是 sealed interface，每加一个页面都必须在这里补一条 when 分支（无 else），
 *   这正是我们要的"漏了新页面会被编译发现"；而若让每个页面自己写 scope，
 *   漏写时编译不报错，只会静默不显示背景图。
 *
 * ⚠️ 归类风险（加页面时必读）：
 *   上面那条"编译发现"只兜住"漏写分支"，兜不住"随手归类"。当新页面不属于任何既有档位
 *   （例如将来多出一条独立的分区线）时，为了过编译把它塞进某一档是可以编译的，
 *   后果是这个新页面会**静默地**按那一档的规则画/不画背景，没人会收到报错。
 *   现状：四个档位覆盖 AppScreen 全部 11 个分支（见 ui/navigation/ScreenScope.kt 的
 *   backgroundScope()），那里是唯一认识 AppScreen 全集的地方。加页面时请一并复核那张表。
 *
 * 「全局」为什么是一条**普通档位**而不是"全选"：
 *   需求原话是"可以选择应用在哪个页面，便签，课表，我的，全局"——它与其他四项**并列**，
 *   不是"全选/清空"那种元操作。语义上勾它 = 所有页面都画，但它和"课表+我的+便签"三档
 *   同时勾在 UI 里是两回事（前者是开关，后者是三档叠加）；存进去就是集合里含不含 GLOBAL。
 *   这样用户先勾全局、再勾掉全局换成三个档位，中间没有任何一步需要"清空再勾"，
 *   也不需要额外维护"全选复选框与四档勾选状态是否一致"这种永远同步不完的状态。
 *
 * 归类口径（页面上会照此写文案，不含糊）：
 *   - 便签   ：待办清单页（M12 需求五新增的第三个底栏项）
 *   - 我的   ：「我的」根页及其二级页（权限 / 关于 / 自定义背景）
 *   - 课表   ：其余全部页面（周视图、添加/编辑课程、导入中心、清理、分享、学期设置）
 *     —— 学期设置虽从「我的」进，但它是学期数据编辑页（与课程编辑同属"填表"场景），
 *        归到"课表"这一侧在可读性上更合理。
 */
package com.gould.xputimetable.ui.background

/** 背景作用域（存进 DataStore 用 name()，故枚举名不可随意改）。 */
enum class BackgroundScope {
    /** 全局：所有页面。勾选它即「任何页面都画背景」，但不排斥与其他档位同时勾选。 */
    GLOBAL,

    /** 课表：周视图 + 一切填表 / 导入页。 */
    TIMETABLE,

    /** 我的：「我的」根页与它的二级页。 */
    PROFILE,

    /** 便签：待办清单页。 */
    NOTE,
}

/** 界面上展示的分组名（设置页"作用范围"一栏的四个选项）。 */
val BackgroundScope.label: String
    get() = when (this) {
        BackgroundScope.GLOBAL -> "全局"
        BackgroundScope.TIMETABLE -> "课表"
        BackgroundScope.PROFILE -> "我的"
        BackgroundScope.NOTE -> "便签"
    }

/**
 * 把一组作用域压成一句人话（「我的」页那行摘要用；纯函数，可单测）。
 *
 * 三种形态，各自对应用户心里的不同状态：
 *   - 没勾任何项 → 「未选择」（**不写"全部"**：用户确实一项都没勾，
 *     写"全部"会让他以为出了 bug 去反复点开关）
 *   - 勾了「全局」→ 「全局」。此时其余勾选是冗余的（全局已经覆盖它们），
 *     不罗列出来，否则摘要会变成"全局、课表、我的"这种自相矛盾的话。
 *   - 其它多选 → 按枚举声明顺序（课表/我的/便签）列出，不按点击顺序 ——
 *     摘要每次进页面必须长得一样，否则用户会以为是随机顺序。
 *
 * @param scopes 用户勾选的集合（顺序无关）
 * @return 摘要文案
 */
fun scopeSummary(scopes: Set<BackgroundScope>): String = when {
    scopes.isEmpty() -> "未选择"
    BackgroundScope.GLOBAL in scopes -> BackgroundScope.GLOBAL.label
    else -> scopes.sortedBy { it.ordinal }.joinToString("、") { it.label }
}
